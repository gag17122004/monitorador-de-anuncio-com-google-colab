import requests
from bs4 import BeautifulSoup
import pandas as pd
import time

# --- CONFIGURAÇÃO DE ACESSO ---
# Simulando um navegador real para evitar bloqueios automáticos
HEADERS = {
    "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/119.0.0.0 Safari/537.36",
    "Accept-Language": "pt-BR,pt;q=0.9,en-US;q=0.8,en;q=0.7"
}

# --- LISTA DE PRODUTOS PARA MONITORAR ---
# ADICIONE OS LINKS DOS SEUS CONCORRENTES ABAIXO
meus_concorrentes = [
    {
        "nome": "Produto Exemplo ML",
        "url": "COLE_AQUI_O_LINK_DO_MERCADO_LIVRE",
        "meu_preco": 100.00
    },
    {
        "nome": "Produto Exemplo Shopee",
        "url": "https://shopee.com.br/Kit-1000-Envelope-de-Seguran%C3%A7a-Embalagem-Envio-12x18-15x20-15x25-15x30-20x20-19x25-20x30-25x30-26x36-i.1540555083.23794273753?extraParams=%7B%22display_model_id%22%3A119869706264%2C%22model_selection_logic%22%3A3%7D&sp_atk=aae3fd1d-aaa3-48fc-a57a-f2d7ffcd8b9a&xptdk=aae3fd1d-aaa3-48fc-a57a-f2d7ffcd8b9a",
        "meu_preco": 50.00
    }
]

def extrair_preco(item):
    url = item['url']
    try:
        response = requests.get(url, headers=HEADERS, timeout=15)
        soup = BeautifulSoup(response.text, 'html.parser')
        preco_encontrado = None

        # Lógica para Mercado Livre
        if "mercadolivre.com.br" in url:
            inteiro = soup.find("span", {"class": "andes-money-amount__fraction"})
            centavos = soup.find("span", {"class": "andes-money-amount__cents"})
            if inteiro:
                valor = inteiro.text.replace(".", "")
                if centavos:
                    valor += "." + centavos.text
                preco_encontrado = float(valor)

        # Lógica para Shopee (via Metadados SEO)
        elif "shopee.com.br" in url:
            meta_preco = soup.find("meta", {"property": "product:price:amount"})
            if meta_preco:
                preco_encontrado = float(meta_preco['content'])

        return preco_encontrado
    except Exception as e:
        return None

# --- EXECUÇÃO DO MONITORAMENTO ---
resultados = []

print("🚀 Iniciando monitoramento de preços...")

for item in meus_concorrentes:
    print(f"Checando: {item['nome']}...")
    preco_concorrente = extrair_preco(item)

    if preco_concorrente:
        diferenca = item['meu_preco'] - preco_concorrente
        if preco_concorrente < item['meu_preco']:
            status = "🚨 BAIXAR PREÇO"
        else:
            status = "✅ PREÇO COMPETITIVO"
    else:
        status = "❌ Erro na Leitura"
        preco_concorrente = 0

    resultados.append({
        "Produto": item['nome'],
        "Preço Concorrente": f"R$ {preco_concorrente:.2f}",
        "Meu Preço": f"R$ {item['meu_preco']:.2f}",
        "Situação": status
    })
    time.sleep(2) # Pausa curta para não sobrecarregar os sites

# Exibir Tabela Final
df = pd.DataFrame(resultados)
print("\n--- RELATÓRIO DE ESTRATÉGIA ---")
display(df)